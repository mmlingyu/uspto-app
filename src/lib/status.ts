export function translateStatus(code: number | null, description: string | null): { zh: string | null; en: string | null } {
  if (code != null && STATUS_ZH[code]) return { zh: STATUS_ZH[code], en: description }
  return { zh: null, en: description }
}

export function aliveLabel(alive: boolean | null): string {
  if (alive === true) return '有效'
  if (alive === false) return '失效'
  return '未知'
}
